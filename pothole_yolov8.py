import os
import json

# Google Drive folders
drive_images_folder = os.path.join(
    drive_folder,
    "pothole_images"
)

# Prepare the JSON structure
results_data = {
    "video": {
        "name": video_name,
        "duration_seconds": round(duration_seconds, 3),
        "fps": fps,
        "width": width,
        "height": height,
        "total_frames": total_video_frames,
        "processed_frames": frame_count,
        "total_detections": total_detections,
        "unique_track_ids": len(unique_tracks)
    },
    "events": []
}

# Add event information and its Google Drive image path
for track in sorted(
    unique_tracks.values(),
    key=lambda item: item["track_id"]
):
    image_filename = os.path.basename(track["image_path"])

    event = {
        "track_id": track["track_id"],
        "confidence": track["confidence"],
        "frame_number": track["frame_number"],
        "timestamp_seconds": track["timestamp_seconds"],
        "image_name": image_filename,
        "image_drive_path": os.path.join(
            drive_images_folder,
            image_filename
        )
    }

    results_data["events"].append(event)

# Save the JSON file to Google Drive
json_path = os.path.join(drive_folder, "results.json")

with open(json_path, "w", encoding="utf-8") as file:
    json.dump(
        results_data,
        file,
        indent=4,
        ensure_ascii=False
    )

print("JSON created successfully!")
print("File location:", json_path)
print("Number of events:", len(results_data["events"]))















