from ultralytics import YOLO
from google.colab import files
import cv2
import os

# 1. Load the trained YOLO model for pothole detection
model = YOLO(weights_path)

# 2. Upload the road video from your computer
uploaded = files.upload()

if not uploaded:
    raise ValueError("No video was uploaded")

# Get the uploaded video's name and full path
video_name = next(iter(uploaded.keys()))
video_path = os.path.join("/content", video_name)

# 3. Open the uploaded video and check that it is readable
cap = cv2.VideoCapture(video_path)

if not cap.isOpened():
    raise ValueError("Could not open the input video")

# 4. Extract the video's FPS, width, height, and original frame count
fps = cap.get(cv2.CAP_PROP_FPS)
width = int(cap.get(cv2.CAP_PROP_FRAME_WIDTH))
height = int(cap.get(cv2.CAP_PROP_FRAME_HEIGHT))
total_video_frames = int(cap.get(cv2.CAP_PROP_FRAME_COUNT))

if fps <= 0:
    raise ValueError("Invalid video FPS")

# Calculate video duration in seconds
duration_seconds = total_video_frames / fps

# 5. Create the output video file for frames with detection boxes and track IDs
output_path = "/content/pothole_tracking.mp4"

fourcc = cv2.VideoWriter_fourcc(*"mp4v")
out = cv2.VideoWriter(
    output_path,
    fourcc,
    fps,
    (width, height)
)

if not out.isOpened():
    cap.release()
    raise RuntimeError("Could not create output video")

# 6. Initialize counters and storage for detection information
frame_count = 0
total_detections = 0
unique_tracks = {}
images_folder = "/content/pothole_images"
os.makedirs(images_folder, exist_ok=True)
# 7. Read and process the video one frame at a time
try:
    while True:

        # Read the next frame from the video
        ret, frame = cap.read()

        # Stop when there are no more frames to read
        if not ret:
            break

        # Detect potholes and track them across consecutive frames
        results = model.track(
            source=frame,
            persist=True,
            tracker="bytetrack.yaml",
            conf=0.35,
            verbose=False
        )

        result = results[0]
        # Draw boxes and labels on the full frame
        annotated_frame = result.plot()


        # Count the detections found in the current frame

        # Count detections in the current frame
        detections = len(result.boxes) if result.boxes is not None else 0
        total_detections += detections

        # Keep the highest-confidence detection for each track ID
        if result.boxes is not None and result.boxes.id is not None:

            timestamp_seconds = frame_count / fps

            for box in result.boxes:
                track_id = int(box.id.item())
                confidence = float(box.conf.item())

                if (
                    track_id not in unique_tracks
                    or confidence > unique_tracks[track_id]["confidence"]
                ):
                    # Save the full annotated frame
                    image_path = os.path.join(
                        images_folder,
                        f"pothole_{track_id}.jpg"
                    )

                    if cv2.imwrite(image_path, annotated_frame):
                        unique_tracks[track_id] = {
                            "track_id": track_id,
                            "frame_number": frame_count + 1,
                            "timestamp_seconds": round(timestamp_seconds, 3),
                            "confidence": round(confidence, 4),
                            "image_path": image_path
                        }


        # Draw boxes and save the annotated frame
        out.write(annotated_frame)

        # Move to the next frame
        frame_count += 1


finally:
    # Release video resources even if processing stops unexpectedly
    cap.release()
    out.release()


print("Video processing completed!")
print("Video name:", video_name)
print("Frames processed:", frame_count)
print("Original video frames:", total_video_frames)
print("Video duration (seconds):", round(duration_seconds, 3))
print("FPS:", fps)
print("Resolution:", f"{width}x{height}")
print("Total detections across frames:", total_detections)
print("Unique track IDs:", len(unique_tracks))
